"""Pack the Assets folder into packed_assets.py.

The game imports packed_assets, and PyInstaller always bundles imported modules,
so the images end up inside the .exe however it is built (plain
`pyinstaller poo_boy.py` included), without any --add-data or .spec settings.

Running the game from source (`python poo_boy.py`) refreshes packed_assets.py
automatically whenever the Assets folder changes. You can also run this
directly: `python pack_assets.py`.
"""

import base64
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS_DIR = os.path.join(HERE, "Assets")
OUT_FILE = os.path.join(HERE, "packed_assets.py")


def collect():
    files = {}
    for root, _, names in os.walk(ASSETS_DIR):
        for name in names:
            if name.lower().endswith(".png"):
                full = os.path.join(root, name)
                rel = os.path.relpath(full, ASSETS_DIR).replace(os.sep, "/")
                with open(full, "rb") as f:
                    files[rel] = base64.b64encode(f.read()).decode("ascii")
    return files


def render(files):
    lines = ['"""Generated by pack_assets.py from the Assets folder. Do not edit by hand."""', "", "FILES = {"]
    for rel, data in sorted(files.items()):
        lines.append(f"    {rel!r}: (")
        for i in range(0, len(data), 100):
            lines.append(f"        {data[i:i + 100]!r}")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def update():
    """Rewrite packed_assets.py if the Assets folder has changed. Returns True if it was rewritten."""
    if not os.path.isdir(ASSETS_DIR):
        return False
    text = render(collect())
    try:
        with open(OUT_FILE, encoding="utf-8") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    try:
        with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    except OSError:
        return False
    return True


if __name__ == "__main__":
    print("packed_assets.py updated" if update() else "packed_assets.py already up to date")
